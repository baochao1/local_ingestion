CREATE UNIQUE INDEX uq_lte_edge ON lineage_table_edge (src_fqn, tgt_fqn) WHERE deleted_at IS NULL;
CREATE INDEX idx_lte_src ON lineage_table_edge (src_fqn) WHERE deleted_at IS NULL;
CREATE INDEX idx_lte_tgt ON lineage_table_edge (tgt_fqn) WHERE deleted_at IS NULL;

CREATE TABLE lineage_column_edge (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    BIGINT      NOT NULL DEFAULT 0,
    src_fqn      TEXT        NOT NULL,
    tgt_fqn      TEXT        NOT NULL,
    src_column_id BIGINT,
    tgt_column_id BIGINT,
