-- 8. 变更事件（按月分区）
-- =============================================================================
CREATE TABLE change_event (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    detected_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    scan_run_id  BIGINT,
    datasource_id BIGINT,
    entity_type  TEXT        NOT NULL,   -- table / column
    entity_id    BIGINT,
    entity_fqn   TEXT,
    change_type  TEXT        NOT NULL,   -- added / deleted / modified / renamed
    severity     TEXT        NOT NULL,   -- breaking / structural / descriptive
    before_json  JSONB,
    after_json   JSONB,
    notified     BOOLEAN     NOT NULL DEFAULT FALSE,
    ack_status   TEXT        NOT NULL DEFAULT 'pending',  -- pending / closed (T-204)
    ack_action   TEXT,                                    -- acknowledged / rejected / ignored
    ack_by       TEXT,
    ack_at       TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (id, detected_at),
    CONSTRAINT ck_change_type CHECK (change_type IN ('table_added','table_removed','table_renamed','column_added','column_removed','column_renamed','type_changed','nullable_changed','comment_changed')),
    CONSTRAINT ck_change_sev  CHECK (severity IN ('breaking','structural','descriptive')),
    CONSTRAINT ck_change_ack  CHECK (ack_status IN ('pending','closed'))
) PARTITION BY RANGE (detected_at);
CREATE INDEX idx_change_run ON change_event (scan_run_id);
CREATE INDEX idx_change_sev ON change_event (severity, detected_at DESC);
CREATE INDEX idx_change_entity ON change_event (entity_type, entity_fqn, detected_at DESC);
CREATE INDEX idx_change_ack ON change_event (ack_status, detected_at DESC);

