-- =============================================================================
-- 1. 租户（预留，单租户时全填 0）
-- =============================================================================
CREATE TABLE tenant (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          TEXT        NOT NULL,
    name          TEXT        NOT NULL,
    enabled       BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_tenant_code ON tenant (code);

-- =============================================================================
-- 2. 数据源与凭据
-- =============================================================================
CREATE TABLE datasource (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       BIGINT      NOT NULL DEFAULT 0,
    code            TEXT        NOT NULL,
    name            TEXT        NOT NULL,
    ds_type         TEXT        NOT NULL,   -- mysql / postgres / snowflake / sqlserver / bigquery
    host            TEXT,
    port            INTEGER,

    -- 环境标识、分组与负责人（FR-1.7 ~ FR-1.9）
    environment     TEXT,                    -- prod / test / dev
    group_name      TEXT,
    owner_business  TEXT,
    owner_technical TEXT,

    -- 采集策略
    enabled         BOOLEAN     NOT NULL DEFAULT TRUE,
    scan_enabled    BOOLEAN     NOT NULL DEFAULT TRUE,
    sampling_enabled BOOLEAN    NOT NULL DEFAULT FALSE,  -- 默认关闭，见 FR-8 / Q7
    scan_config     JSONB       NOT NULL DEFAULT '{}'::jsonb,
    --   {"include_schemas":[], "exclude_schemas":[], "include_tables":[],
    --    "exclude_tables":[], "max_concurrency":4, "cron":"0 2 * * *"}
    sampling_config JSONB       NOT NULL DEFAULT '{}'::jsonb,
    --   {"sample_rate":1.0, "max_rows":100000, "timeout_seconds":60,
    --    "large_table_threshold":100000000, "sensitive_blacklist":[]}

    -- 能力位（由连接器探测或配置，FR-8.5）
    supports_sampling  BOOLEAN  NOT NULL DEFAULT FALSE,
    supports_lineage   BOOLEAN  NOT NULL DEFAULT FALSE,
    supports_profiling BOOLEAN  NOT NULL DEFAULT FALSE,

    -- 健康度
    last_scan_at    TIMESTAMPTZ,
    last_scan_status TEXT,
    last_error      TEXT,

    deleted_at      TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_datasource_type CHECK (
        ds_type IN ('mysql','postgres','snowflake','sqlserver','bigquery','other')
    )
);
CREATE UNIQUE INDEX uq_datasource_code ON datasource (code) WHERE deleted_at IS NULL;
CREATE INDEX idx_datasource_tenant ON datasource (tenant_id) WHERE deleted_at IS NULL;

COMMENT ON COLUMN datasource.scan_config      IS '采集策略：黑白名单、并发、调度';
COMMENT ON COLUMN datasource.sampling_config  IS '采样策略：采样率、上限、超时、大表熔断阈值、敏感列黑名单';
COMMENT ON COLUMN datasource.supports_sampling IS 'MySQL 无 TABLESAMPLE，需由方言层置位并走替代策略';

-- 凭据独立表：支持多版本轮换，密文由应用层加密（密钥不入库）
CREATE TABLE datasource_credential (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    datasource_id  BIGINT      NOT NULL REFERENCES datasource (id),
    version        INTEGER     NOT NULL DEFAULT 1,
    username       TEXT,
    credential_enc BYTEA       NOT NULL,     -- 应用层加密后的口令/密钥材料
    enc_algo       TEXT        NOT NULL DEFAULT 'AES-256-GCM',
    is_active      BOOLEAN     NOT NULL DEFAULT TRUE,
    verified_at    TIMESTAMPTZ,
    expires_at     TIMESTAMPTZ,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_dscred_active
    ON datasource_credential (datasource_id) WHERE is_active;
CREATE INDEX idx_dscred_ds ON datasource_credential (datasource_id, version DESC);

-- =============================================================================
-- 3. 元数据实体（catalog_*）
-- =============================================================================
CREATE TABLE catalog_database (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     BIGINT      NOT NULL DEFAULT 0,
    datasource_id BIGINT      NOT NULL REFERENCES datasource (id),
    name          TEXT        NOT NULL,
    fqn           TEXT        NOT NULL,
    description   TEXT,
    owner         TEXT,
    tags          JSONB       NOT NULL DEFAULT '[]'::jsonb,
    properties    JSONB       NOT NULL DEFAULT '{}'::jsonb,
    deleted_at    TIMESTAMPTZ,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_catdb_fqn ON catalog_database (fqn) WHERE deleted_at IS NULL;
CREATE INDEX idx_catdb_ds ON catalog_database (datasource_id) WHERE deleted_at IS NULL;

CREATE TABLE catalog_schema (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     BIGINT      NOT NULL DEFAULT 0,
    datasource_id BIGINT      NOT NULL REFERENCES datasource (id),
    database_id   BIGINT      NOT NULL REFERENCES catalog_database (id),
    name          TEXT        NOT NULL,
    fqn           TEXT        NOT NULL,
    description   TEXT,
    owner         TEXT,
    tags          JSONB       NOT NULL DEFAULT '[]'::jsonb,
    properties    JSONB       NOT NULL DEFAULT '{}'::jsonb,
    deleted_at    TIMESTAMPTZ,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_catsch_fqn ON catalog_schema (fqn) WHERE deleted_at IS NULL;
CREATE INDEX idx_catsch_db ON catalog_schema (database_id) WHERE deleted_at IS NULL;
CREATE INDEX idx_catsch_ds ON catalog_schema (datasource_id) WHERE deleted_at IS NULL;

CREATE TABLE catalog_table (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     BIGINT      NOT NULL DEFAULT 0,
    datasource_id BIGINT      NOT NULL REFERENCES datasource (id),
    schema_id     BIGINT      NOT NULL REFERENCES catalog_schema (id),
    name          TEXT        NOT NULL,
    fqn           TEXT        NOT NULL,
    table_type    TEXT,                      -- TABLE / VIEW / MATERIALIZED_VIEW / EXTERNAL
    description   TEXT,
    owner         TEXT,
    tags          JSONB       NOT NULL DEFAULT '[]'::jsonb,
    properties    JSONB       NOT NULL DEFAULT '{}'::jsonb,

    -- 冗余：详情接口一次读取，避免 N 行 join（决策 A）
    columns_json  JSONB       NOT NULL DEFAULT '[]'::jsonb,
    column_count  INTEGER     NOT NULL DEFAULT 0,

    -- 结构签名 + 分级冗余（决策 E / F）
    struct_hash   TEXT,
    grade_level   SMALLINT,
    grade_code    TEXT,

    deleted_at    TIMESTAMPTZ,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_table_grade CHECK (grade_level IS NULL OR grade_level BETWEEN 1 AND 9)
);
CREATE UNIQUE INDEX uq_cattab_fqn ON catalog_table (fqn) WHERE deleted_at IS NULL;
CREATE INDEX idx_cattab_keyset ON catalog_table (fqn, id) WHERE deleted_at IS NULL;
CREATE INDEX idx_cattab_ds_keyset ON catalog_table (datasource_id, fqn, id) WHERE deleted_at IS NULL;
CREATE INDEX idx_cattab_schema ON catalog_table (schema_id, name) WHERE deleted_at IS NULL;
CREATE INDEX idx_cattab_grade ON catalog_table (grade_level) WHERE deleted_at IS NULL;
CREATE INDEX idx_cattab_name_trgm ON catalog_table USING gin (name gin_trgm_ops);
CREATE INDEX idx_cattab_tags ON catalog_table USING gin (tags jsonb_path_ops);

COMMENT ON COLUMN catalog_table.columns_json IS '字段冗余缓存，以 catalog_column 为准，可由重建任务按 table_id 重刷';
COMMENT ON COLUMN catalog_table.struct_hash  IS 'md5(按 ordinal 拼接的字段签名)，用于增量判定与 Diff 前置过滤';

-- 核心大表：字段（MVP 不分区，触发条件见设计文档 §5.1）
CREATE TABLE catalog_column (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        BIGINT      NOT NULL DEFAULT 0,
    datasource_id    BIGINT      NOT NULL REFERENCES datasource (id),
    table_id         BIGINT      NOT NULL REFERENCES catalog_table (id),
    name             TEXT        NOT NULL,
    fqn              TEXT        NOT NULL,
    ordinal_position INTEGER,
    data_type        TEXT,                   -- 归一化类型
    data_type_display TEXT,                  -- 源库原始类型串
    data_length      INTEGER,
    numeric_precision INTEGER,
    numeric_scale    INTEGER,
    nullable         BOOLEAN     NOT NULL DEFAULT TRUE,
    default_value    TEXT,
    description      TEXT,

    children         JSONB       NOT NULL DEFAULT '[]'::jsonb,  -- 嵌套类型不打散（决策 B）
    tags             JSONB       NOT NULL DEFAULT '[]'::jsonb,
    properties       JSONB       NOT NULL DEFAULT '{}'::jsonb,

    struct_hash      TEXT,
    grade_level      SMALLINT,
    grade_code       TEXT,

    deleted_at       TIMESTAMPTZ,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_column_grade CHECK (grade_level IS NULL OR grade_level BETWEEN 1 AND 9)
);
CREATE UNIQUE INDEX uq_catcol_fqn ON catalog_column (fqn) WHERE deleted_at IS NULL;
CREATE INDEX idx_catcol_keyset ON catalog_column (fqn, id) WHERE deleted_at IS NULL;
CREATE INDEX idx_catcol_ds_keyset ON catalog_column (datasource_id, fqn, id) WHERE deleted_at IS NULL;
CREATE INDEX idx_catcol_table ON catalog_column (table_id, ordinal_position) WHERE deleted_at IS NULL;
CREATE INDEX idx_catcol_grade ON catalog_column (grade_level) WHERE deleted_at IS NULL;
CREATE INDEX idx_catcol_datatype ON catalog_column (data_type) WHERE deleted_at IS NULL;
CREATE INDEX idx_catcol_name_trgm ON catalog_column USING gin (name gin_trgm_ops);
CREATE INDEX idx_catcol_tags ON catalog_column USING gin (tags jsonb_path_ops);

-- =============================================================================
-- 4. 数据画像与质量
-- =============================================================================
CREATE TABLE table_profile (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     BIGINT      NOT NULL DEFAULT 0,
    datasource_id BIGINT      NOT NULL REFERENCES datasource (id),
    table_id      BIGINT      NOT NULL REFERENCES catalog_table (id),
    row_count     BIGINT,
    column_count  INTEGER,
    size_bytes    BIGINT,
    -- per-column 统计：{"col": {"null_count":..,"distinct_count":..,"min":..,
    --                   "max":..,"mean":..,"stddev":..,"top_values":[..]}}
    stats         JSONB       NOT NULL DEFAULT '{}'::jsonb,
    sample_rate   NUMERIC(6,4),
    sampled_rows  BIGINT,
    profiled_at   TIMESTAMPTZ,
    duration_ms   INTEGER,
    status        TEXT        NOT NULL DEFAULT 'pending',
    error_message TEXT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_profile_status CHECK (status IN ('pending','running','success','failed','skipped'))
);
CREATE UNIQUE INDEX uq_profile_table ON table_profile (table_id);
CREATE INDEX idx_profile_ds ON table_profile (datasource_id, profiled_at DESC);

CREATE TABLE quality_rule (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     BIGINT      NOT NULL DEFAULT 0,
    code          TEXT        NOT NULL,
    name          TEXT        NOT NULL,
    rule_type     TEXT        NOT NULL,   -- not_null / unique / range_check / pattern_match / referential / custom_sql
    target_type   TEXT        NOT NULL,   -- table / column
    definition    JSONB       NOT NULL DEFAULT '{}'::jsonb,
    severity      TEXT        NOT NULL DEFAULT 'warning',
    enabled       BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_qrule_code ON quality_rule (code);

CREATE TABLE quality_result (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_run_id   BIGINT,
    table_id      BIGINT      NOT NULL REFERENCES catalog_table (id),
    column_id     BIGINT      REFERENCES catalog_column (id),
    rule_id       BIGINT      NOT NULL REFERENCES quality_rule (id),
    passed        BOOLEAN     NOT NULL,
    metric_value  NUMERIC,
    detail        JSONB       NOT NULL DEFAULT '{}'::jsonb,
    executed_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_qresult_table ON quality_result (table_id, executed_at DESC);
CREATE INDEX idx_qresult_rule ON quality_result (rule_id, executed_at DESC);

