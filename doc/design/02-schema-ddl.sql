CREATE INDEX idx_etag_key ON entity_tag (tag_key) WHERE deleted_at IS NULL;
CREATE INDEX idx_etag_grade ON entity_tag (grade_level) WHERE deleted_at IS NULL;

COMMENT ON COLUMN entity_tag.source IS 'manual 来源的标签，自动引擎不得覆盖（FR-9.5）';

