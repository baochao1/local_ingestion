BEGIN;

CREATE EXTENSION IF NOT EXISTS pg_trgm;      -- 表名/字段名模糊检索
CREATE EXTENSION IF NOT EXISTS btree_gin;    -- 标量 + JSONB 组合索引

-- 如需独立 schema，取消下一行注释并统一替换表名前缀
-- CREATE SCHEMA IF NOT EXISTS mdm;
