CREATE TABLE classification_tag (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT      NOT NULL DEFAULT 0,
    tag_key     TEXT        NOT NULL,        -- pii_phone / pii_idcard / ...
    tag_name    TEXT        NOT NULL,        -- 手机号
    category    TEXT,                        -- PII / 财务 / 业务
    grade_level SMALLINT,
    grade_code  TEXT,                        -- L1..L4
    color       TEXT,
    description TEXT,
    enabled     BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_clstag_grade CHECK (grade_level IS NULL OR grade_level BETWEEN 1 AND 9)
);
CREATE UNIQUE INDEX uq_clstag_key ON classification_tag (tag_key);
CREATE INDEX idx_clstag_grade ON classification_tag (grade_level);

CREATE TABLE classification_rule (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT      NOT NULL DEFAULT 0,
    tag_key     TEXT        NOT NULL,
    rule_kind   TEXT        NOT NULL,   -- column_name / regex / data_type / sample_verify
    pattern     TEXT,                   -- 词典词或正则
