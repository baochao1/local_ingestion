CREATE UNIQUE INDEX uq_account ON account (datasource_id, account_name, host_pattern) WHERE deleted_at IS NULL;

CREATE TABLE account_grant (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     BIGINT      NOT NULL DEFAULT 0,
    datasource_id BIGINT      NOT NULL REFERENCES datasource (id),
    account_id    BIGINT      REFERENCES account (id),
    privilege     TEXT        NOT NULL,   -- SELECT / INSERT / UPDATE / DELETE / ALL
    object_type   TEXT        NOT NULL,   -- database / schema / table / column
